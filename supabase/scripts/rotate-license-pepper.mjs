import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const [outputSql, outputSecret] = process.argv.slice(2);
if (!outputSql || !outputSecret) {
  console.error("Usage: node rotate-license-pepper.mjs <rotation.sql> <secret.env>");
  process.exit(2);
}

const adminKey = process.env.CSKIN_ADMIN_KEY?.trim();
const baseUrl = (process.env.CSKIN_AUTH_BASE_URL || "https://license.re2347.ccwu.cc").replace(/\/+$/, "");
if (!adminKey) throw new Error("CSKIN_ADMIN_KEY is required");

async function fetchPage(page) {
  const response = await fetch(`${baseUrl}/v1/admin/licenses?page=${page}&pageSize=100`, {
    headers: { "X-Admin-Key": adminKey },
  });
  const body = await response.json();
  if (!response.ok || !body.ok || !Array.isArray(body.items)) {
    throw new Error(`admin list failed: HTTP ${response.status}`);
  }
  return body;
}

const first = await fetchPage(1);
const total = Number(first.total);
if (!Number.isSafeInteger(total) || total < 1) throw new Error("admin list returned an invalid total");
const pages = Math.ceil(total / 100);
const licenses = [...first.items];
for (let page = 2; page <= pages; page += 1) licenses.push(...(await fetchPage(page)).items);
if (licenses.length !== total) throw new Error(`expected ${total} licenses, received ${licenses.length}`);

const pepper = crypto.randomBytes(48).toString("base64url");
const key = crypto.createHash("sha256").update(pepper, "utf8").digest();
const normalizeCode = (value) => value.replace(/[^a-z0-9]/gi, "").toUpperCase();
const sqlLiteral = (value) => `'${String(value).replaceAll("'", "''")}'`;
const updates = [];

for (const license of licenses) {
  if (typeof license.license_id !== "string" || typeof license.code !== "string" || !license.code.trim()) {
    throw new Error(`license ${license.license_id || "unknown"} has no recoverable code`);
  }
  const normalized = normalizeCode(license.code);
  if (normalized.length < 16) throw new Error(`license ${license.license_id} has an invalid code`);
  const codeHash = crypto.createHmac("sha256", pepper).update(`license:${normalized}`, "utf8").digest("hex");
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv("aes-256-gcm", key, iv);
  const ciphertext = Buffer.concat([cipher.update(license.code, "utf8"), cipher.final(), cipher.getAuthTag()]).toString("base64url");
  updates.push(
    `UPDATE licenses SET code_hash=${sqlLiteral(codeHash)}, code_ciphertext=${sqlLiteral(ciphertext)}, code_iv=${sqlLiteral(iv.toString("base64url"))}, version=version+1 WHERE license_id=${sqlLiteral(license.license_id)};`,
  );
}

const sql = [
  "-- Generated by rotate-license-pepper.mjs.",
  "-- The new pepper is stored separately; this file never contains it.",
  "-- Existing leases use the old pepper and are intentionally removed.",
  "BEGIN;",
  ...updates,
  "DELETE FROM leases;",
  "COMMIT;",
  "",
].join("\n");

fs.mkdirSync(path.dirname(path.resolve(outputSql)), { recursive: true });
fs.mkdirSync(path.dirname(path.resolve(outputSecret)), { recursive: true });
fs.writeFileSync(path.resolve(outputSql), sql, "utf8");
fs.writeFileSync(path.resolve(outputSecret), `LICENSE_PEPPER=${pepper}\n`, "utf8");
console.log(JSON.stringify({
  licenseCount: licenses.length,
  leasesWillBeRemoved: true,
  sqlPath: path.resolve(outputSql),
  secretPath: path.resolve(outputSecret),
}));
